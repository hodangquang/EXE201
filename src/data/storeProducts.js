export const getStoreProductById = (id) => {
  if (!id) return STORE_PRODUCTS[0];
  const query = String(id).toLowerCase();
  const found = STORE_PRODUCTS.find(
    (p) =>
      String(p.id).toLowerCase() === query ||
      (p.alias && p.alias.some((a) => a.toLowerCase() === query))
  );
  return found || STORE_PRODUCTS[0];
};
